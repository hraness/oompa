/**
 * Digest of a reviewed disposition matrix bound to one Codex pin. The bump
 * script recomputes this for the requested version; the runtime compares it
 * with the checked-in value before serving any request or notification.
 */
export const codexMatrixDigest = (
  version: string,
  matrix: Readonly<Record<string, string>>,
): string => {
  const signature = `${version}\n${Object.entries(matrix)
    .map(([method, disposition]) => `${method}:${disposition}`)
    .join("\n")}`;
  return createHash("sha256").update(signature).digest("hex");
};

const liveAcceptanceCommandPattern = /^\/bin\/echo oompa-live-tool-progress \| \/usr\/bin\/tee \.\/(\.oompa-live-command-proof-[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.txt)$/u;
const liveAcceptanceCommandDigestDomain = "hra:live-acceptance-command:v1\0";

/**
 * Projects a digest only for Oompa's exact, deliberately non-secret live-gate
 * command grammar. Arbitrary provider commands must never become public
 * equality oracles.
 */
export const safeLiveAcceptanceCommandDigest = (command: string): string | undefined => {
  const match = liveAcceptanceCommandPattern.exec(command);
  const fileName = match?.[1];
  if (fileName === undefined) return undefined;
  const canonical = `/bin/echo oompa-live-tool-progress | /usr/bin/tee ./${fileName}`;
  if (command !== canonical) return undefined;
  return createHash("sha256")
    .update(liveAcceptanceCommandDigestDomain, "utf8")
    .update(canonical, "utf8")
    .digest("hex");
};

