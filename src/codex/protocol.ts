export type PinnedCodexNotificationMethod = keyof typeof PINNED_CODEX_NOTIFICATION_MATRIX;

/**
 * SHA-256 of that executable's generated experimental `ServerNotification.ts`.
 * The runtime package does not retain generated TypeScript schemas, so the
 * live trust chain is: dependency-integrity-locked package, exact manifest and
 * initialized app-server versions, then this reviewed matrix signature. Tests
 * regenerate the schema files through the pinned executable and compare their
 * digests and method unions with `pin.ts` and the reviewed matrices;
 * `bun run codex:bump` rewrites `pin.ts` for a new version.
 */
export const PINNED_CODEX_NOTIFICATION_SCHEMA_DIGEST =
  PINNED_CODEX_SCHEMA_DIGESTS["ServerNotification.ts"];

export function assertPinnedCodexNotificationMatrix(): void {
  const digest = codexMatrixDigest(CODEX_PIN, PINNED_CODEX_NOTIFICATION_MATRIX);
  if (digest !== PINNED_CODEX_MATRIX_DIGESTS.notification) {
    throw new CodexError(
      "RUNTIME_MISMATCH",
      "The pinned Codex notification matrix does not match its reviewed schema",
    );
  }
}

export function codexNotificationDisposition(
  method: string,
): CodexNotificationDisposition | null {
  return Object.hasOwn(PINNED_CODEX_NOTIFICATION_MATRIX, method)
    ? PINNED_CODEX_NOTIFICATION_MATRIX[method as PinnedCodexNotificationMethod]
    : null;
}

