const plainJsonObject = (value: unknown): value is Readonly<Record<string, unknown>> =>
  value !== null
  && typeof value === "object"
  && !Array.isArray(value)
  && (Object.getPrototypeOf(value) === Object.prototype || Object.getPrototypeOf(value) === null)
  && Object.getOwnPropertySymbols(value).length === 0;

const commandApprovalDecisionContractUnsupported = (): CodexError => new CodexError(
  "UNSUPPORTED_CAPABILITY",
  "The command approval uses a decision contract Oompa cannot safely represent.",
);

/**
 * The pinned `FileChangeRequestApprovalParams` has no `availableDecisions`
 * field, while its fixed response contract admits four literals. Oompa exposes
 * only the two non-granting responses so an absent or unexpected input field
 * can never create blind file-write authority.
 */
const safeFileChangeApprovalDecisions: readonly InteractionDecision[] = Object.freeze([
  "decline",
  "cancel",
]);

const isKnownCommandApprovalAmendment = (value: unknown): boolean => {
  if (!plainJsonObject(value)) return false;
  const entries = Object.entries(value);
  if (entries.length !== 1) return false;
  const entry = entries[0];
  if (entry === undefined) return false;
  const [kind, payload] = entry;
  if (!plainJsonObject(payload)) return false;
  const payloadKey = kind === "acceptWithExecpolicyAmendment"
    ? "execpolicy_amendment"
    : kind === "applyNetworkPolicyAmendment"
      ? "network_policy_amendment"
      : null;
  return payloadKey !== null && Object.hasOwn(payload, payloadKey);
};

const commandApprovalDecisions = (value: unknown): readonly InteractionDecision[] => {
  if (value === undefined || value === null) throw commandApprovalDecisionContractUnsupported();
  const decisions: InteractionDecision[] = [];
  const seen = new Set<InteractionDecision>();
  const add = (decision: InteractionDecision): void => {
    if (seen.has(decision)) return;
    seen.add(decision);
    decisions.push(decision);
  };
  for (const candidate of array(value, "available decisions", (item) => item, 20)) {
    if (candidate === "accept") {
      add("once");
      continue;
    }
    if (candidate === "acceptForSession") {
      add("session");
      continue;
    }
    if (candidate === "decline" || candidate === "cancel") {
      add(candidate);
      continue;
    }
    if (isKnownCommandApprovalAmendment(candidate)) continue;
    throw commandApprovalDecisionContractUnsupported();
  }
  if (decisions.length === 0) throw commandApprovalDecisionContractUnsupported();
  return decisions;
};

export function validateMcpFormSubmission(
  fields: readonly McpFormField[],
  value: unknown,
): Readonly<Record<string, unknown>> {
  try {
    if (!plainJsonObject(value)) throw invalidMcpFormSubmission();
    const serialized = canonicalJson(value);
    if (
      canonicalTextEncoder.encode(serialized).byteLength
        > remoteInteractionAnswerLimits.providerJsonBytes
    ) {
      throw invalidMcpFormSubmission();
    }
    const byName = new Map(fields.map((field) => [field.name, field] as const));
    const keys = Object.keys(value);
    if (keys.some((key) => !byName.has(key))) throw invalidMcpFormSubmission();
    for (const field of fields) {
      if (!Object.hasOwn(value, field.name)) {
        if (field.required) throw invalidMcpFormSubmission();
        continue;
      }
      const submitted = value[field.name];
      if (field.type === "string") {
        if (typeof submitted !== "string") throw invalidMcpFormSubmission();
        const length = Array.from(submitted).length;
        if (
          length < field.minLength
          || length > field.maxLength
          || !validateStringFormat(submitted, field.format)
        ) throw invalidMcpFormSubmission();
      } else if (field.type === "number" || field.type === "integer") {
        if (
          typeof submitted !== "number"
          || !Number.isFinite(submitted)
          || (field.type === "integer" && !Number.isSafeInteger(submitted))
          || (field.minimum !== null && submitted < field.minimum)
          || (field.maximum !== null && submitted > field.maximum)
        ) throw invalidMcpFormSubmission();
      } else if (field.type === "boolean") {
        if (typeof submitted !== "boolean") throw invalidMcpFormSubmission();
      } else if (field.type === "single_select") {
        if (typeof submitted !== "string" || !field.choices.includes(submitted)) {
          throw invalidMcpFormSubmission();
        }
      } else {
        const multiSelect = field as Extract<McpFormField, { readonly type: "multi_select" }>;
        if (
          !Array.isArray(submitted)
          || submitted.length < multiSelect.minItems
          || submitted.length > multiSelect.maxItems
          || submitted.some((entry) => typeof entry !== "string" || !multiSelect.choices.includes(entry))
          || new Set(submitted).size !== submitted.length
        ) throw invalidMcpFormSubmission();
      }
    }
    return JSON.parse(serialized) as Readonly<Record<string, unknown>>;
  } catch (error: unknown) {
    if (error instanceof CodexError && error.code === "INVALID_INPUT") throw error;
    throw invalidMcpFormSubmission();
  }
}

export function parseBrokeredCodexServerRequest(input: {
  readonly authority: CodexAuthority;
  readonly connectionId: string;
  readonly requestId: ProviderRequestId;
  readonly method: BrokeredCodexServerRequestMethod;
  readonly params: unknown;
}): ParsedBrokeredCodexServerRequest {
  const authority = validateAuthority(input.authority);
  const privateParams = parseCanonicalParams(input.params);
  const threadId = identifier(privateParams.threadId, "server request thread id");
  const turnId = nullableRequestIdentifier(privateParams.turnId, "server request turn id");
  const itemId = nullableRequestIdentifier(privateParams.itemId, "server request item id");
  const approvalId = nullableRequestIdentifier(privateParams.approvalId, "server request approval id");
  const provider: ProviderInteractionAuthority = {
    profileId: authority.profileId,
    processGeneration: authority.processGeneration,
    provider: authority.provider,
    providerAccountId: authority.providerAccountId,
    bindingGeneration: authority.bindingGeneration,
    connectionId: input.connectionId,
    requestId: input.requestId,
    method: input.method,
    requestDigest: digestCodexJson(privateParams),
    threadId,
    turnId,
    itemId,
    approvalId,
  };
  const providerTimeout = privateParams.autoResolutionMs;
  const parsedProviderTimeout = providerTimeout === undefined || providerTimeout === null
    ? INTERACTION_MAX_PENDING_MS
    : safeInteger(providerTimeout, "server request auto-resolution interval");
  if (parsedProviderTimeout < 0) {
    throw protocol("server request auto-resolution interval cannot be negative");
  }
  const timeoutMs = Math.min(parsedProviderTimeout, INTERACTION_MAX_PENDING_MS);

  if (input.method === "item/commandExecution/requestApproval") {
    if (turnId === null || itemId === null) throw protocol("command approval omitted turn or item context");
    const availableDecisions = commandApprovalDecisions(privateParams.availableDecisions);
    const privateApprovalAuthority = commandApprovalAuthority(privateParams);
    const commandClass = classifyApprovalCommand(privateParams.command);
    const reason = nullableSafeDisplayText(privateParams.reason, "command approval reason", 4_096);
    return {
      provider,
      kind: "command_approval",
      blocking: true,
      timeoutMs,
      display: {
        kind: "command_approval",
        summary: `Allow ${commandClass}`,
        reason,
        commandClass,
        workingDirectory: nullableSafeDisplayText(privateParams.cwd, "command cwd", 1_024),
        availableDecisions: [...availableDecisions],
      },
      privateParams,
      privateApprovalAuthority,
    };
  }
  if (input.method === "item/fileChange/requestApproval") {
    if (turnId === null || itemId === null) throw protocol("file approval omitted turn or item context");
    // The pinned Codex file-change callback omits affected paths and change
    // detail, so Oompa has never had enough to support an informed human
    // decision. The request is still admitted as a durable interaction (never
    // exposing a private approval authority, since none exists), but every
    // autorespond mode leaves it pending. Blind acceptance is a global safety
    // refusal; a foreground operator may still decline the request.
    const availableDecisions = safeFileChangeApprovalDecisions;
    const reason = nullableSafeDisplayText(privateParams.reason, "file change approval reason", 4_096);
    const grantRoot = nullableSafeDisplayText(privateParams.grantRoot, "file change grant root", 1_024);
    return {
      provider,
      kind: "file_change_approval",
      blocking: true,
      timeoutMs,
      display: {
        kind: "file_change_approval",
        summary: "Allow the proposed file changes",
        reason,
        grantRoot,
        availableDecisions: [...availableDecisions],
      },
      privateParams,
      privateApprovalAuthority: null,
    };
  }
  if (input.method === "item/permissions/requestApproval") {
    if (turnId === null || itemId === null) throw protocol("permission approval omitted turn or item context");
    const privateApprovalAuthority = permissionApprovalAuthority(privateParams);
    if (privateApprovalAuthority.kind !== "permission_approval") {
      throw protocol("permission approval authority kind changed during parsing");
    }
    const requested = requestedPermissionAuthority(privateApprovalAuthority.permissions)
      .map((permission) => ({ name: permission.displayName }));
    const reason = nullableSafeDisplayText(privateParams.reason, "permission approval reason", 4_096);
    return {
      provider,
      kind: "permission_approval",
      blocking: true,
      timeoutMs,
      display: {
        kind: "permission_approval",
        summary: "Allow the requested additional permissions",
        reason,
        requested,
        allowsSessionScope: true,
      },
      privateParams,
      privateApprovalAuthority,
    };
  }
  if (input.method === "item/tool/requestUserInput") {
    if (turnId === null || itemId === null) throw protocol("user input request omitted turn or item context");
    const questions = array(privateParams.questions, "user input questions", (value, index) => {
      const question = record(value, `user input question ${String(index)}`);
      const parsedOptions = question.options === null
        ? null
        : array(question.options, "user input options", (option, optionIndex) => {
            const parsed = record(option, `user input option ${String(optionIndex)}`);
            const label = safeDisplayTextResult(parsed.label, "user input option label", 512);
            const description = safeDisplayTextResult(
              parsed.description,
              "user input option description",
              2_048,
            );
            if (label.text.length === 0) throw protocol("user input option label is empty after safe rendering");
            return {
              exact: label.exact && description.exact,
              option: { description: description.text, label: label.text },
            };
          }, 20);
      const options = parsedOptions?.map(({ option }) => option) ?? null;
      if (
        options !== null
        && new Set(options.map((option) => option.label)).size !== options.length
      ) throw protocol("user input option labels must be unique");
      const header = safeDisplayTextResult(question.header, "user input header", 256);
      const prompt = safeDisplayTextResult(question.question, "user input question", 4_096);
      if (header.text.length === 0 || prompt.text.length === 0) {
        throw protocol("user input question text is empty after safe rendering");
      }
      const remoteAnswerable = header.exact
        && prompt.exact
        && (parsedOptions?.every(({ exact }) => exact) ?? true);
      return {
        id: identifier(question.id, "user input question id"),
        header: header.text,
        question: prompt.text,
        options: options === null ? null : [...options],
        allowsOther: boolean(question.isOther, "user input allows other"),
        secret: boolean(question.isSecret, "user input secret flag"),
        ...(remoteAnswerable ? { remoteAnswerable: true as const } : {}),
      };
    }, 3);
    if (questions.length < 1) throw protocol("user input request omitted questions");
    if (new Set(questions.map((question) => question.id)).size !== questions.length) {
      throw protocol("user input question ids must be unique");
    }
    const blocking = boolean(privateParams.isBlocking, "user input blocking flag");
    return {
      provider,
      kind: "user_input",
      blocking,
      timeoutMs,
      display: {
        kind: "user_input",
        summary: questions.length === 1 ? "Codex needs one answer" : `Codex needs ${String(questions.length)} answers`,
        blocking,
        questions: [...questions],
      },
      privateParams,
      privateApprovalAuthority: null,
    };
  }

  const mode = string(privateParams.mode, "MCP elicitation mode", { min: 1, max: 64 });
  if (mode !== "form" && mode !== "openai/form" && mode !== "url") {
    throw protocol("MCP elicitation mode is unsupported");
  }
  if (mode === "url") {
    throw new CodexError(
      "UNSUPPORTED_CAPABILITY",
      "MCP URL elicitation requires a protected browser handoff that Oompa does not expose.",
    );
  }
  if (mode === "openai/form") throw unsupportedMcpForm();
  assertMcpFormMetadataIsNonApproval(privateParams._meta);
  const fields = parseMcpFormFields(privateParams.requestedSchema);
  string(privateParams.message, "MCP elicitation message", { max: 4 * 1024 * 1024 });
  const serverName = identifier(privateParams.serverName, "MCP server name");
  return {
    provider,
    kind: "mcp_elicitation",
    blocking: true,
    timeoutMs,
    display: {
      kind: "mcp_elicitation",
      summary: PUBLIC_MCP_FORM_SUMMARY,
      serverName,
      mode: "form",
      url: null,
      mayContainSecrets: true,
      fields: [...fields],
    },
    privateParams,
    privateApprovalAuthority: null,
  };
}

export function compileCodexInteractionResponse(input: {
  readonly method: BrokeredCodexServerRequestMethod;
  readonly kind: InteractionKind;
  readonly privateParams: Readonly<Record<string, unknown>>;
  readonly resolution: InteractionResolution;
}): unknown {
  const { method, kind, privateParams, resolution } = input;
  if (method === "item/commandExecution/requestApproval" || method === "item/fileChange/requestApproval") {
    const expectedKind = method === "item/commandExecution/requestApproval"
      ? "command_approval"
      : "file_change_approval";
    if (kind !== expectedKind || resolution.kind !== "approval_decision") {
      throw new CodexError("INVALID_INPUT", "interaction resolution kind does not match the provider request");
    }
    if (
      method === "item/commandExecution/requestApproval"
      && !commandApprovalDecisions(privateParams.availableDecisions).includes(resolution.decision)
    ) {
      throw new CodexError("INVALID_INPUT", "the command approval does not offer that decision");
    }
    if (
      method === "item/fileChange/requestApproval"
      && !safeFileChangeApprovalDecisions.includes(resolution.decision)
    ) {
      throw new CodexError("INVALID_INPUT", "the file change approval does not offer that decision");
    }
    const decision = resolution.decision === "once"
      ? "accept"
      : resolution.decision === "session"
        ? "acceptForSession"
        : resolution.decision;
    return { decision };
  }
  if (method === "item/permissions/requestApproval") {
    if (kind !== "permission_approval") {
      throw new CodexError("INVALID_INPUT", "interaction resolution kind does not match the permission request");
    }
    if (resolution.kind === "approval_decision") {
      if (resolution.decision !== "decline") {
        throw new CodexError(
          "INVALID_INPUT",
          "permission approval supports an exact requested subset or decline",
        );
      }
      return { permissions: {}, scope: "turn" };
    }
    if (resolution.kind !== "permission_grant") {
      throw new CodexError("INVALID_INPUT", "permission approval requires a permission grant");
    }
    const requested = new Map(
      requestedPermissionAuthority(privateParams.permissions)
        .map((permission) => [permission.displayName, permission] as const),
    );
    const selected = resolution.permissions.map((name) => {
      const permission = requested.get(name);
      if (permission === undefined) {
        throw new CodexError("INVALID_INPUT", "selected permissions exceed the requested profile");
      }
      return [permission.providerName, permission.value] as const;
    });
    if (selected.length !== new Set(selected.map(([name]) => name)).size) {
      throw new CodexError("INVALID_INPUT", "selected permission names must be unique");
    }
    return {
      permissions: safeInteractionJson(Object.fromEntries(selected)),
      scope: resolution.scope ?? "turn",
    };
  }
  if (method === "item/tool/requestUserInput") {
    if (kind !== "user_input" || resolution.kind !== "user_answers") {
      throw new CodexError("INVALID_INPUT", "user input requires exact question answers");
    }
    const questions = array(privateParams.questions, "user input questions", (value) => {
      const question = record(value, "user input question");
      const id = identifier(question.id, "user input question id");
      const allowsOther = boolean(question.isOther, "user input allows other");
      const optionLabels = question.options === null
        ? null
        : array(question.options, "user input options", (option) => {
            const parsed = record(option, "user input option");
            return string(parsed.label, "user input option label", { max: 4 * 1024 * 1024 });
          }, 20);
      return { allowsOther, id, optionLabels };
    }, 3);
    const expected = new Map(questions.map((question) => [question.id, question] as const));
    const submitted = new Map(Object.entries(resolution.answers));
    if (
      submitted.size !== expected.size
      || [...submitted.keys()].some((id) => !expected.has(id))
    ) {
      throw new CodexError("INVALID_INPUT", "answers must match the exact requested question ids");
    }
    for (const question of expected.values()) {
      const answers = submitted.get(question.id)?.answers;
      if (
        answers === undefined
        || (question.optionLabels !== null
          && !question.allowsOther
          && answers.some((answer) => !question.optionLabels?.includes(answer)))
      ) {
        throw new CodexError("INVALID_INPUT", "answers must match the requested choices");
      }
    }
    return { answers: safeInteractionJson(resolution.answers) };
  }
  if (kind !== "mcp_elicitation" || resolution.kind !== "mcp_submission") {
    throw new CodexError("INVALID_INPUT", "MCP elicitation requires an MCP submission");
  }
  if (resolution.action !== "accept" && resolution.content !== undefined) {
    throw new CodexError("INVALID_INPUT", "declined or canceled MCP elicitation cannot include content");
  }
  const mode = privateParams.mode;
  if (mode !== "form") throw new CodexError(
    "UNSUPPORTED_CAPABILITY",
    "The MCP elicitation mode is not available through Oompa.",
  );
  const content = resolution.action === "accept"
    ? validateMcpFormSubmission(
      parseMcpFormFields(privateParams.requestedSchema),
      resolution.content ?? {},
    )
    : null;
  return {
    action: resolution.action,
    content: resolution.action === "accept" ? safeInteractionJson(content) : null,
    _meta: null,
  };
}

export function parseFact(method: string, params: unknown): CodexFact {
  const root = record(params ?? {}, `${method} notification`);
  const disposition = codexNotificationDisposition(method);
  if (disposition === "ignored") {
    return {
      type: "notificationIgnored",
      method: method as PinnedCodexNotificationMethod,
    };
  }
  if (method === "account/updated") {
    return {
      type: "accountUpdated",
      authMode: nullableString(root.authMode, "account authMode", 128),
      planType: nullableString(root.planType, "account planType", 128),
    };
  }
  if (method === "account/rateLimits/updated") {
    // Sparse pushes only wake an authoritative read. Their mutable values are
    // deliberately not projected into Oompa state or reset decisions.
    return { type: "rateLimitsUpdated" };
  }
  if (method === "account/login/completed") {
    return {
      type: "loginCompleted",
      loginId: nullableString(root.loginId, "login id", 512),
      success: boolean(root.success, "login success"),
    };
  }
  if (method === "thread/started") {
    // Reduced only for a spawned subagent: the parent thread id routes the
    // fact to the Oompa session that owns the conversation, and the bounded
    // nickname, role, and depth are the only fields retained. Every other
    // thread start stays discarded.
    const thread = record(root.thread, "started thread");
    const parentThreadId = nullableString(thread.parentThreadId ?? null, "parent thread id", 512);
    if (parentThreadId === null || parentThreadId.length === 0) {
      return { type: "notificationIgnored", method: "thread/started" };
    }
    const nickname = subagentLabel(thread.agentNickname, "subagent nickname");
    const role = subagentLabel(thread.agentRole, "subagent role");
    const depth = subagentSpawnDepth(thread.source);
    return {
      type: "subagentThreadStarted",
      threadId: parentThreadId,
      agentThreadId: identifier(thread.id, "subagent thread id"),
      ...(depth === undefined ? {} : { depth }),
      ...(nickname === undefined ? {} : { nickname }),
      ...(role === undefined ? {} : { role }),
    };
  }
  if (method === "thread/status/changed") {
    return {
      type: "threadStatusChanged",
      threadId: identifier(root.threadId, "thread id"),
      status: parseThreadStatus(root.status),
    };
  }
  if (method === "thread/closed") {
    return {
      type: "threadStatusChanged",
      threadId: identifier(root.threadId, "thread id"),
      status: { type: "notLoaded" },
    };
  }
  if (method === "thread/deleted") {
    return {
      type: "threadDeleted",
      threadId: identifier(root.threadId, "thread id"),
    };
  }
  if (method === "turn/started" || method === "turn/completed") {
    return {
      type: method === "turn/started" ? "turnStarted" : "turnCompleted",
      threadId: identifier(root.threadId, "thread id"),
      turn: parseTurn(root.turn, 0),
    };
  }
  if (method === "thread/name/updated") {
    return {
      type: "threadNameUpdated",
      threadId: identifier(root.threadId, "thread id"),
      name: nullableString(root.name, "thread name", 1_024),
    };
  }
  if (method === "thread/compacted") {
    // The pinned `ContextCompactedNotification` is exactly
    // `{ threadId, turnId }`. No other provider payload is retained.
    return {
      type: "threadCompaction",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      outcome: "completed",
    };
  }
  if (method === "item/started" || method === "item/completed") {
    const item = record(root.item, "thread item");
    const itemKind = string(item.type, "thread item type", { min: 1, max: 128 });
    const status = item.status === undefined
      ? undefined
      : string(item.status, "thread item status", { min: 1, max: 128 });
    const server = itemKind === "mcpToolCall"
      ? identifier(item.server, "MCP server")
      : undefined;
    const tool = itemKind === "mcpToolCall" || itemKind === "dynamicToolCall"
      ? identifier(item.tool, "tool name")
      : undefined;
    const liveAcceptanceCommandDigest = itemKind === "commandExecution"
      ? safeLiveAcceptanceCommandDigest(string(item.command, "command", { max: 1_000_000 }))
      : undefined;
    const commandClass = itemKind === "commandExecution" && item.command !== undefined
      ? classifyApprovalCommand(item.command)
      : undefined;
    const subagent = itemKind === "subAgentActivity"
      ? {
          agentThreadId: identifier(item.agentThreadId, "subagent thread id"),
          kind: oneOf(item.kind, "subagent activity kind", CODEX_SUBAGENT_ACTIVITY_KINDS),
        }
      : undefined;
    return {
      type: method === "item/started" ? "itemStarted" : "itemCompleted",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      itemId: identifier(item.id, "thread item id"),
      itemKind,
      ...(commandClass === undefined ? {} : { commandClass }),
      ...(liveAcceptanceCommandDigest === undefined ? {} : { liveAcceptanceCommandDigest }),
      ...(status === undefined ? {} : { status }),
      ...(server === undefined ? {} : { server }),
      ...(tool === undefined ? {} : { tool }),
      ...(subagent === undefined ? {} : { subagent }),
    };
  }
  if (method === "item/agentMessage/delta") {
    return {
      type: "assistantDelta",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      itemId: identifier(root.itemId, "thread item id"),
      text: safeDisplayText(root.delta, "assistant delta", 32_768),
    };
  }
  if (method === "item/reasoning/summaryTextDelta") {
    const summaryIndex = safeInteger(root.summaryIndex, "reasoning summary index");
    if (summaryIndex < 0 || summaryIndex > 10_000) {
      throw protocol("reasoning summary index is outside its bounded range");
    }
    return {
      type: "reasoningSummaryDelta",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      itemId: identifier(root.itemId, "thread item id"),
      summaryIndex,
      text: safeDisplayText(root.delta, "reasoning summary delta", 32_768),
    };
  }
  if (
    method === "item/commandExecution/outputDelta"
    || method === "item/fileChange/outputDelta"
  ) {
    const delta = string(root.delta, "tool output delta", { max: 4 * 1024 * 1024 });
    return {
      type: "toolProgress",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      itemId: identifier(root.itemId, "thread item id"),
      toolKind: method === "item/commandExecution/outputDelta" ? "command" : "file_change",
      status: "running",
      outputBytesObserved: canonicalTextEncoder.encode(delta).byteLength,
    };
  }
  if (method === "item/mcpToolCall/progress") {
    string(root.message, "MCP progress message", { max: 4 * 1024 * 1024 });
    return {
      type: "toolProgress",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      itemId: identifier(root.itemId, "thread item id"),
      toolKind: "mcp",
      status: "running",
    };
  }
  if (method === "turn/plan/updated") {
    const steps = array(root.plan, "turn plan", (value, index) => {
      const step = record(value, `turn plan step ${String(index)}`);
      const status = oneOf(
        step.status,
        "turn plan step status",
        ["pending", "inProgress", "completed"] as const,
      );
      return {
        text: safeDisplayText(step.step, "turn plan step", 1_024),
        status: status === "inProgress" ? "in_progress" as const : status,
      };
    }, 100);
    const explanation = root.explanation === null
      ? undefined
      : safeDisplayText(root.explanation, "turn plan explanation", 4_096);
    return {
      type: "planUpdated",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      steps,
      ...(explanation === undefined ? {} : { explanation }),
    };
  }
  if (method === "turn/diff/updated") {
    const diff = string(root.diff, "turn diff", { max: 4 * 1024 * 1024 });
    const changedFiles = Math.min(1_000_000, diff.match(/^diff --git /gmu)?.length ?? 0);
    return {
      type: "diffUpdated",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      changedFiles,
      patchBytesObserved: canonicalTextEncoder.encode(diff).byteLength,
    };
  }
  if (method === "item/fileChange/patchUpdated") {
    let patchBytesObserved = 0;
    const changes = array(root.changes, "file changes", (value, index) => {
      const change = record(value, `file change ${String(index)}`);
      identifier(change.path, "file change path");
      const diff = string(change.diff, "file change diff", { max: 4 * 1024 * 1024 });
      patchBytesObserved += canonicalTextEncoder.encode(diff).byteLength;
      return undefined;
    }, 1_000);
    if (!Number.isSafeInteger(patchBytesObserved)) throw protocol("file change patch bytes overflowed");
    return {
      type: "diffUpdated",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      changedFiles: changes.length,
      patchBytesObserved,
    };
  }
  if (method === "thread/tokenUsage/updated") {
    const usage = record(root.tokenUsage, "thread token usage");
    const total = record(usage.total, "thread total token usage");
    const nonnegativeToken = (value: unknown, label: string): number => {
      const parsed = safeInteger(value, label);
      if (parsed < 0) throw protocol(`${label} must be nonnegative`);
      return parsed;
    };
    const modelContextWindow = usage.modelContextWindow === null
      ? null
      : nonnegativeToken(usage.modelContextWindow, "model context window");
    if (modelContextWindow !== null && modelContextWindow < 1) {
      throw protocol("model context window must be positive");
    }
    return {
      type: "tokenUsageUpdated",
      threadId: identifier(root.threadId, "thread id"),
      turnId: identifier(root.turnId, "turn id"),
      inputTokens: nonnegativeToken(total.inputTokens, "input tokens"),
      cachedInputTokens: nonnegativeToken(total.cachedInputTokens, "cached input tokens"),
      outputTokens: nonnegativeToken(total.outputTokens, "output tokens"),
      reasoningOutputTokens: nonnegativeToken(total.reasoningOutputTokens, "reasoning output tokens"),
      totalTokens: nonnegativeToken(total.totalTokens, "total tokens"),
      modelContextWindow,
    };
  }
  if (method === "warning") {
    if (root.threadId === null) {
      return { type: "notificationIgnored", method: "warning" };
    }
    return {
      type: "providerWarning",
      threadId: identifier(root.threadId, "warning thread id"),
      code: "provider_warning",
      message: "Codex reported a provider warning.",
    };
  }
  if (method === "error") {
    record(root.error, "provider error");
    return {
      type: "providerError",
      threadId: identifier(root.threadId, "error thread id"),
      turnId: identifier(root.turnId, "error turn id"),
      code: "provider_error",
      message: "Codex reported a provider error.",
      terminal: !boolean(root.willRetry, "provider error retry flag"),
    };
  }
  if (method === "serverRequest/resolved") {
    return {
      type: "serverRequestResolved",
      threadId: identifier(root.threadId, "resolved request thread id"),
      requestId: parseProviderRequestId(root.requestId),
    };
  }
  if (disposition !== null) {
    throw protocol(`reviewed ${method} notification has no Oompa parser`);
  }
  // A method outside the reviewed notification union is retained only as a
  // bounded notice so the daemon can expose protocol drift without preserving
  // the foreign payload.
  return { type: "protocolNotice", method: string(method, "notification method", { max: 512 }) };
}

export function resolvePreset(
  snapshot: CodexCapabilitySnapshot,
  alias: PresetAlias,
  requirement: PresetRequirement,
  fast: boolean,
): ResolvedPreset {
  if (
    requirement.effort === "provider-default"
    || !isAdmittedPresetRequirement(alias, requirement)
  ) {
    throw new CodexError(
      "UNSUPPORTED_CAPABILITY",
      `${alias} requested an unadmitted exact Oompa model and reasoning tuple`,
    );
  }
  const candidates = snapshot.models.filter((model) => model.model === requirement.model);
  const model = candidates[0];
  if (
    model === undefined
    || candidates.length !== 1
    || !model.supportedReasoningEfforts.includes(requirement.effort)
  ) {
    throw new CodexError(
      "UNSUPPORTED_CAPABILITY",
      `${alias} requires exactly ${requirement.model} with ${requirement.effort} reasoning for this account generation`,
    );
  }
  const effort: ReasoningEffort = requirement.effort;
  let serviceTier: string | null = null;
  if (fast) {
    const tier = model.serviceTiers.find((candidate) => candidate.id === "priority");
    if (tier === undefined) {
      throw new CodexError(
        "UNSUPPORTED_CAPABILITY",
        `Fast mode is unavailable for ${model.displayName}`,
      );
    }
    serviceTier = tier.id;
  }
  return { alias, model: model.model, effort, serviceTier, fast };
}

function safeHttpUrl(value: unknown, label: string): string {
  const parsed = string(value, label, { min: 1, max: 16_384 });
  let url: URL;
  try {
    url = new URL(parsed);
  } catch {
    throw protocol(`${label} is not a URL`);
  }
  if (url.protocol !== "https:" && !(url.protocol === "http:" && isLoopback(url.hostname))) {
    throw protocol(`${label} must use HTTPS or a loopback callback`);
  }
  if (url.username !== "" || url.password !== "") throw protocol(`${label} contains credentials`);
  return url.toString();
}

function isLoopback(hostname: string): boolean {
  return hostname === "localhost" || hostname === "127.0.0.1" || hostname === "[::1]";
}

function nullableNonnegativeInteger(value: unknown, label: string): number | null {
  return value === null ? null : nonnegativeInteger(value, label);
}

function nonnegativeInteger(value: unknown, label: string): number {
  const parsed = safeInteger(value, label);
  if (parsed < 0) throw protocol(`${label} must be nonnegative`);
  return parsed;
}

function nullableNonnegativeNumber(value: unknown, label: string): number | null {
  return value === null ? null : nonnegativeNumber(value, label);
}

function nonnegativeNumber(value: unknown, label: string): number {
  const parsed = number(value, label);
  if (parsed < 0) throw protocol(`${label} must be nonnegative`);
  return parsed;
}

function unixSecondsToMilliseconds(value: unknown, label: string): number {
  const seconds = nonnegativeInteger(value, label);
  const milliseconds = seconds * 1_000;
  if (!Number.isSafeInteger(milliseconds)) {
    throw protocol(`${label} exceeds the safe Unix-millisecond range`);
  }
  return milliseconds;
}

export function validateAuthority(authority: unknown): CodexAuthority {
  if (!plainJsonObject(authority)) {
    throw new CodexError("INVALID_INPUT", "Codex provider-account authority is invalid");
  }
  const profileId = identifier(authority.profileId, "profile id");
  if (typeof authority.processGeneration !== "number"
    || !Number.isSafeInteger(authority.processGeneration) || authority.processGeneration < 1) {
    throw new CodexError("INVALID_INPUT", "process generation must be a positive integer");
  }
  const providerAccountId = codexProviderAccountIdSchema.safeParse(authority.providerAccountId);
  if (
    authority.provider !== "codex"
    || !providerAccountId.success
    || typeof authority.bindingGeneration !== "number"
    || !Number.isSafeInteger(authority.bindingGeneration)
    || authority.bindingGeneration < 1
  ) {
    throw new CodexError("INVALID_INPUT", "Codex provider-account authority is invalid");
  }
  return {
    profileId,
    processGeneration: authority.processGeneration,
    provider: "codex",
    providerAccountId: providerAccountId.data,
    bindingGeneration: authority.bindingGeneration,
  };
}

export function boundedPageLimit(value: number | undefined, max = 200): number {
  const selected = value ?? Math.min(50, max);
  if (!Number.isSafeInteger(selected) || selected < 1 || selected > max) {
    throw new CodexError("INVALID_INPUT", `page limit must be between 1 and ${String(max)}`);
  }
  return selected;
}

export function boundedText(value: string, label: string, max = 1_000_000): string {
  if (typeof value !== "string" || value.length < 1 || value.length > max) {
    throw new CodexError("INVALID_INPUT", `${label} must be a non-empty bounded string`);
  }
  return value;
}

export function boundedIdentifier(value: string, label: string): string {
  try {
    return identifier(value, label);
  } catch (error) {
    throw new CodexError("INVALID_INPUT", `${label} is invalid`, { cause: error });
  }
}

